CREATE INDEX IDX_CONFERENCE_REVIEWER_CONF_STATUS ON CONFERENCE_REVIEWER (CONFERENCE_ID, MEMBERSHIP_STATUS, REVIEWER_ID);
CREATE INDEX IDX_CONFERENCE_REVIEWER_REVIEWER ON CONFERENCE_REVIEWER (REVIEWER_ID, CONFERENCE_ID);
CREATE INDEX IDX_REVIEWER_BID_REVIEWER_CONF ON REVIEWER_BID (REVIEWER_ID, CONFERENCE_ID, BID_ID);
CREATE INDEX IDX_REVIEWER_BID_MANUSCRIPT ON REVIEWER_BID (MANUSCRIPT_ID, BID_VALUE);

CREATE OR REPLACE TRIGGER TRG_CONFERENCE_REVIEWER_BI
BEFORE INSERT ON CONFERENCE_REVIEWER
FOR EACH ROW
BEGIN
  IF :NEW.CONFERENCE_REVIEWER_ID IS NULL THEN
    :NEW.CONFERENCE_REVIEWER_ID := SEQ_CONFERENCE_REVIEWER.NEXTVAL;
  END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_REVIEWER_BID_BI
BEFORE INSERT ON REVIEWER_BID
FOR EACH ROW
BEGIN
  IF :NEW.BID_ID IS NULL THEN
    :NEW.BID_ID := SEQ_REVIEWER_BID.NEXTVAL;
  END IF;
END;
/
