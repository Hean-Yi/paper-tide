CREATE TABLE CONFERENCE_REVIEWER (
  CONFERENCE_REVIEWER_ID NUMBER(19) NOT NULL,
  CONFERENCE_ID NUMBER(19) NOT NULL,
  REVIEWER_ID NUMBER(19) NOT NULL,
  MAX_LOAD NUMBER(10) NOT NULL,
  RESEARCH_AREAS_JSON CLOB NOT NULL,
  MEMBERSHIP_STATUS VARCHAR2(20) NOT NULL,
  INVITED_BY NUMBER(19) NOT NULL,
  JOINED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_CONFERENCE_REVIEWER PRIMARY KEY (CONFERENCE_REVIEWER_ID),
  CONSTRAINT UK_CONFERENCE_REVIEWER UNIQUE (CONFERENCE_ID, REVIEWER_ID),
  CONSTRAINT CK_CONFERENCE_REVIEWER_STATUS CHECK (MEMBERSHIP_STATUS IN ('ACTIVE', 'REMOVED')),
  CONSTRAINT CK_CONFERENCE_REVIEWER_MAX_LOAD CHECK (MAX_LOAD BETWEEN 1 AND 20)
);

CREATE TABLE REVIEWER_BID (
  BID_ID NUMBER(19) NOT NULL,
  CONFERENCE_ID NUMBER(19) NOT NULL,
  MANUSCRIPT_ID NUMBER(19) NOT NULL,
  REVIEWER_ID NUMBER(19) NOT NULL,
  BID_VALUE VARCHAR2(30) NOT NULL,
  CONFLICT_DECLARED NUMBER(1) DEFAULT 0 NOT NULL,
  BID_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_REVIEWER_BID PRIMARY KEY (BID_ID),
  CONSTRAINT UK_REVIEWER_BID UNIQUE (CONFERENCE_ID, MANUSCRIPT_ID, REVIEWER_ID),
  CONSTRAINT CK_REVIEWER_BID_VALUE CHECK (BID_VALUE IN ('WANT_TO_REVIEW', 'NEUTRAL', 'DECLINE')),
  CONSTRAINT CK_REVIEWER_BID_CONFLICT CHECK (CONFLICT_DECLARED IN (0, 1))
);

CREATE SEQUENCE SEQ_CONFERENCE_REVIEWER START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_REVIEWER_BID START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

