      DELIVERY_STATUS VARCHAR2(30) NOT NULL,
      CREATED_BY NUMBER(19) NOT NULL,
      CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
      CONSTRAINT PK_OUTBOUND_EMAIL_HISTORY PRIMARY KEY (EMAIL_HISTORY_ID),
      CONSTRAINT CK_OUTBOUND_EMAIL_STATUS CHECK (DELIVERY_STATUS IN ('RECORDED', 'QUEUED', 'SENT', 'FAILED'))
