  add_constraint_if_missing('FK_OUTBOUND_EMAIL_VERSION', 'ALTER TABLE OUTBOUND_EMAIL_HISTORY ADD CONSTRAINT FK_OUTBOUND_EMAIL_VERSION FOREIGN KEY (TEMPLATE_VERSION_ID) REFERENCES EMAIL_TEMPLATE_VERSION (TEMPLATE_VERSION_ID)');
