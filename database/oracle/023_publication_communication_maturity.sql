DECLARE
  PROCEDURE create_table_if_missing(p_table_name IN VARCHAR2, p_table_ddl IN CLOB) IS
    v_count NUMBER;
  BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = UPPER(p_table_name);
    IF v_count = 0 THEN EXECUTE IMMEDIATE p_table_ddl; END IF;
  END;
  PROCEDURE create_sequence_if_missing(p_sequence_name IN VARCHAR2) IS
    v_count NUMBER;
  BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_SEQUENCES WHERE SEQUENCE_NAME = UPPER(p_sequence_name);
    IF v_count = 0 THEN EXECUTE IMMEDIATE 'CREATE SEQUENCE ' || p_sequence_name || ' START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE'; END IF;
  END;
  PROCEDURE add_constraint_if_missing(p_constraint_name IN VARCHAR2, p_constraint_ddl IN VARCHAR2) IS
    v_count NUMBER;
  BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME = UPPER(p_constraint_name);
    IF v_count = 0 THEN EXECUTE IMMEDIATE p_constraint_ddl; END IF;
  END;
  PROCEDURE create_index_if_missing(p_index_name IN VARCHAR2, p_index_ddl IN VARCHAR2) IS
    v_count NUMBER;
  BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_INDEXES WHERE INDEX_NAME = UPPER(p_index_name);
    IF v_count = 0 THEN EXECUTE IMMEDIATE p_index_ddl; END IF;
  END;
BEGIN
  create_table_if_missing('EMAIL_TEMPLATE', q'[
